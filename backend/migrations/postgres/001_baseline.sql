-- PostgreSQL baseline matching the final SQLite schema at version 12.

-- Identity values and TEXT payloads are kept intact during import.

-- Applied with search_path restricted to the Resolve schema and pg_catalog.

CREATE TABLE merchants (
    id TEXT PRIMARY KEY NOT NULL,
    name TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE customer_signins (
    token_hash TEXT PRIMARY KEY NOT NULL,
    email TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    consumed_at TEXT
);

CREATE TABLE customer_sessions (
    token_hash TEXT PRIMARY KEY NOT NULL,
    email TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE TABLE merchant_api_keys (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    token_hash TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL,
    revoked_at TEXT
);

CREATE TABLE captures (
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    capture_id TEXT NOT NULL,
    captured_cents BIGINT NOT NULL CHECK (captured_cents > 0),
    currency TEXT NOT NULL CHECK (currency = 'USD'),
    PRIMARY KEY (merchant_id, capture_id)
);

CREATE TABLE paypal_webhook_events (
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    event_id TEXT NOT NULL,
    payload_sha256 TEXT NOT NULL,
    event_type TEXT NOT NULL,
    capture_id TEXT,
    refund_id TEXT,
    received_at TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('queued','processed','ignored','exception')),
    attempts BIGINT NOT NULL DEFAULT 0,
    next_attempt_at TEXT NOT NULL,
    PRIMARY KEY (merchant_id, event_id)
);

CREATE TABLE cases (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    order_id TEXT NOT NULL,
    complaint TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    commitment_json TEXT,
    status TEXT NOT NULL CHECK (status = 'open'),
    condition_epoch TEXT,
    closed_at TEXT,
    lifecycle_revision BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT cases_approval_owner_idx UNIQUE (id, merchant_id, capture_id),
    CONSTRAINT cases_resolution_owner_idx UNIQUE (id, merchant_id),
    FOREIGN KEY (merchant_id, capture_id)
        REFERENCES captures(merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE refunds (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    refund_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
    currency TEXT NOT NULL CHECK (currency = 'USD'),
    status TEXT NOT NULL CHECK (status IN ('pending', 'completed', 'failed')),
    UNIQUE (merchant_id, refund_id),
    FOREIGN KEY (merchant_id, capture_id)
        REFERENCES captures(merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE paypal_refund_history (
    merchant_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    revision TEXT NOT NULL,
    digest TEXT NOT NULL,
    order_id TEXT NOT NULL,
    identity_hash TEXT NOT NULL,
    checked_at TEXT NOT NULL,
    snapshot_json TEXT NOT NULL,
    PRIMARY KEY (merchant_id, capture_id),
    FOREIGN KEY (merchant_id, capture_id) REFERENCES captures(merchant_id, capture_id)
        ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE condition_checks (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NOT NULL REFERENCES cases(id) DEFERRABLE INITIALLY IMMEDIATE,
    status TEXT NOT NULL CHECK (status IN ('met', 'not_met')),
    evidence_note TEXT NOT NULL,
    recorded_at TEXT NOT NULL,
    recorded_by_merchant_id TEXT REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE refund_approvals (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    case_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    request_id TEXT NOT NULL,
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
    currency TEXT NOT NULL CHECK (currency = 'USD'),
    state_fingerprint TEXT NOT NULL,
    request_json TEXT NOT NULL,
    snapshot_json TEXT NOT NULL,
    decision_note TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('approved', 'revoked', 'expired', 'invalidated')),
    approved_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    status_reason TEXT NOT NULL,
    revocation_reason TEXT,
    UNIQUE (merchant_id, request_id),
    CONSTRAINT approval_execution_owner_idx UNIQUE (id, merchant_id, case_id, capture_id),
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE paypal_capture_verifications (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    merchant_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    paypal_merchant_id TEXT NOT NULL,
    captured_cents BIGINT NOT NULL CHECK (captured_cents > 0),
    currency TEXT NOT NULL CHECK (currency = 'USD'),
    capture_status TEXT NOT NULL,
    checked_at TEXT NOT NULL,
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE case_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    merchant_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    recorded_at TEXT NOT NULL,
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE review_exceptions (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    case_id TEXT,
    capture_id TEXT,
    source_key TEXT NOT NULL,
    reason TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('open','resolved')),
    blocking BIGINT NOT NULL CHECK (blocking IN (0,1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    resolution_note TEXT,
    UNIQUE (merchant_id, source_key),
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE case_attachments (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes BETWEEN 1 AND 2097152),
    sha256 TEXT NOT NULL,
    content BYTEA NOT NULL CHECK (length(content) = size_bytes),
    created_at TEXT NOT NULL,
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE resolution_cases (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    refund_case_id TEXT,
    title TEXT NOT NULL,
    order_reference TEXT,
    created_at TEXT NOT NULL,
    UNIQUE (id, merchant_id),
    UNIQUE (merchant_id, refund_case_id),
    FOREIGN KEY (refund_case_id, merchant_id) REFERENCES cases(id, merchant_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE refund_approval_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id TEXT NOT NULL REFERENCES refund_approvals(id) DEFERRABLE INITIALLY IMMEDIATE,
    event_type TEXT NOT NULL CHECK (event_type IN ('approved', 'revoked', 'expired', 'invalidated')),
    actor_merchant_id TEXT REFERENCES merchants(id) DEFERRABLE INITIALLY IMMEDIATE,
    note TEXT NOT NULL,
    recorded_at TEXT NOT NULL
);

CREATE TABLE refund_executions (
    id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    capture_id TEXT NOT NULL,
    approval_id TEXT NOT NULL UNIQUE,
    request_id TEXT NOT NULL,
    provider_request_id TEXT NOT NULL UNIQUE,
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
    currency TEXT NOT NULL CHECK (currency = 'USD'),
    status TEXT NOT NULL CHECK (status IN ('reserved','submitting','unknown','pending','completed','failed')),
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    approval_json TEXT NOT NULL,
    capture_check_json TEXT NOT NULL,
    provider_request_json TEXT NOT NULL,
    provider_refund_id TEXT,
    provider_refund_json TEXT,
    error_code TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    lease_expires_at TEXT,
    provider_identity_hash TEXT,
    UNIQUE (merchant_id, request_id),
    FOREIGN KEY (case_id, merchant_id, capture_id)
        REFERENCES cases(id, merchant_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    FOREIGN KEY (approval_id, merchant_id, case_id, capture_id)
        REFERENCES refund_approvals(id, merchant_id, case_id, capture_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE resolution_promises (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    resolution_id TEXT NOT NULL,
    merchant_id TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('refund','return','replacement','order_cancellation',
        'subscription','store_credit_or_exchange','billing_correction','dispute_handoff')),
    revision BIGINT NOT NULL CHECK (revision > 0),
    promise_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (id, resolution_id, merchant_id),
    FOREIGN KEY (resolution_id, merchant_id) REFERENCES resolution_cases(id, merchant_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE customer_portal_links (
    resolution_id TEXT PRIMARY KEY NOT NULL,
    merchant_id TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 120),
    show_order_reference BIGINT NOT NULL CHECK (show_order_reference IN (0, 1)),
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    revoked_at TEXT,
    FOREIGN KEY (resolution_id, merchant_id) REFERENCES resolution_cases(id, merchant_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE customer_portal_messages (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    resolution_id TEXT NOT NULL,
    merchant_id TEXT NOT NULL,
    sender TEXT NOT NULL CHECK (sender IN ('customer', 'merchant')),
    request_id TEXT NOT NULL,
    body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
    created_at TEXT NOT NULL,
    UNIQUE (resolution_id, sender, request_id),
    FOREIGN KEY (resolution_id, merchant_id) REFERENCES resolution_cases(id, merchant_id) ON UPDATE CASCADE DEFERRABLE INITIALLY IMMEDIATE
