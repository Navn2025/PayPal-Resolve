-- Shared queries use these only for text JSON paths and ISO timestamp comparisons.
CREATE FUNCTION json_extract(document TEXT, path TEXT) RETURNS TEXT
LANGUAGE SQL IMMUTABLE STRICT
AS $$ SELECT document::jsonb #>> string_to_array(substr(path, 3), '.') $$;

CREATE FUNCTION julianday(iso_time TEXT) RETURNS TIMESTAMPTZ
LANGUAGE SQL STABLE STRICT
AS $$ SELECT iso_time::timestamptz $$;

